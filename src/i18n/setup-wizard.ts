const DICTS: Record<Exclude<Lang, "en">, Record<string, string>> = { "zh-CN": zh, vi };

/** Translate one English wizard string; unknown strings stay English. */
export function tSetup(lang: Lang, english: string, vars?: Record<string, string | number>): string {
  let value = lang === "en" ? english : (DICTS[lang][english] ?? english);
  if (vars) {
    for (const [key, raw] of Object.entries(vars)) {
      value = value.replaceAll(`{${key}}`, String(raw));
    }
  }
  return value;
}
